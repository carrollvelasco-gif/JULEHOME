export function getProduct(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  const sameCategory = products.filter(
    (p) => p.category === product.category && p.id !== product.id,
  );
  const sameCollection = products.filter(
    (p) => p.collection === product.collection && p.id !== product.id,
  );
  const others = products.filter(
    (p) => p.id !== product.id && !sameCategory.includes(p) && !sameCollection.includes(p),
  );
  return [...sameCategory, ...sameCollection, ...others].slice(0, limit);
}

export function getFeaturedProducts(): Product[] {
  return products.filter((p) => p.category === "velas-decorativas").slice(0, 8);
}

export function getBestSellers(): Product[] {
  return products.filter((p) => p.bestSeller).slice(0, 4);
}

export function getChristmasProducts(): Product[] {
  return products.filter(
    (p) => p.collection === "navidad" || p.category === "velas-navidenas",
  );
}

